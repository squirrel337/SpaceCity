def _rasterize(polys: list, w: int, h: int, holes: list = ()) -> bytearray:
    """다각형마다 짝홀 규칙으로 채워 합치고, 구멍은 뺀다. 표본 중심 (x+0.5, y+0.5)."""
    out = bytearray(w * h)
    for group, value in ((polys, 1), (holes, 0)):
        for poly in group:
            edges = []
            n = len(poly)
            for i in range(n):
                la0, lo0 = poly[i]
                la1, lo1 = poly[(i + 1) % n]
                x0 = (lo0 + 180.0) / 360.0 * w
                y0 = (90.0 - la0) / 180.0 * h
                x1 = (lo1 + 180.0) / 360.0 * w
                y1 = (90.0 - la1) / 180.0 * h
                if y0 != y1:
                    edges.append((x0, y0, x1, y1))
            ys = [e[1] for e in edges] + [e[3] for e in edges]
            for y in range(max(0, int(min(ys)) - 1), min(h, int(max(ys)) + 2)):
                yc = y + 0.5
                xs = sorted(x0 + (yc - y0) * (x1 - x0) / (y1 - y0) for x0, y0, x1, y1 in edges
                            if (y0 <= yc < y1) or (y1 <= yc < y0))
                row = y * w
                for k in range(0, len(xs) - 1, 2):
                    a = max(0, int(math.ceil(xs[k] - 0.5)))
                    b = min(w - 1, int(math.floor(xs[k + 1] - 0.5)))
                    if b >= a:
                        out[row + a:row + b + 1] = bytes([value]) * (b - a + 1)
    return out


def _down(mask: bytearray, w: int, h: int, k: int) -> list:
    W2, H2 = w // k, h // k
    res = []
    for y in range(H2):
        for x in range(W2):
            s = 0
            for dy in range(k):
                base = (y * k + dy) * w + x * k
                s += sum(mask[base:base + k])
            res.append(int(round(255.0 * s / (k * k))))
    return res


def _blur(img: list, w: int, h: int, r: int) -> list:
    """상자 흐림 두 번 (가로·세로, 경도는 이어 붙인다)."""
    out = img
    for _ in range(2):
        tmp = [0] * (w * h)
        for y in range(h):
            row = out[y * w:(y + 1) * w]
            acc = sum(row[x % w] for x in range(-r, r + 1))
            for x in range(w):
                tmp[y * w + x] = acc / (2 * r + 1)
                acc += row[(x + r + 1) % w] - row[(x - r) % w]
        res = [0] * (w * h)
        for x in range(w):
            col = [tmp[y * w + x] for y in range(h)]
            acc = sum(col[min(max(y, 0), h - 1)] for y in range(-r, r + 1))
            for y in range(h):
                res[y * w + x] = acc / (2 * r + 1)
                acc += col[min(y + r + 1, h - 1)] - col[max(y - r, 0)]
        out = res
    return [int(round(v)) for v in out]


def earth_rgb() -> bytes:
    land = _down(_rasterize(list(LAND.values()), W * SS, H * SS, list(HOLES.values())), W * SS, H * SS, SS)
    ice = _down(_rasterize(list(ICE.values()), W * SS, H * SS), W * SS, H * SS, SS)
    arid = _blur(_down(_rasterize(list(ARID.values()), W * SS, H * SS), W * SS, H * SS, SS), W, H, 7)
    raw = bytearray()
    for y in range(H):
        raw.append(0)       # 필터 없음 (압축을 풀면 늘 같은 바이트)
        for x in range(W):
            i = y * W + x
            raw += bytes((land[i], min(ice[i], land[i]), min(arid[i], land[i])))
    return bytes(raw)


def png(raw: bytes, w: int = W, h: int = H) -> bytes:
    def chunk(t: bytes, c: bytes) -> bytes:
        return struct.pack(">I", len(c)) + t + c + struct.pack(">I", zlib.crc32(t + c) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def png_pixels(data: bytes) -> bytes:
    """PNG의 압축을 푼 주사선 (필터 0으로 쓴 파일끼리 비교할 때)."""
    i = 8
    idat = b""
    while i < len(data):
        n = struct.unpack(">I", data[i:i + 4])[0]
        t = data[i + 4:i + 8]
        if t == b"IDAT":
            idat += data[i + 8:i + 8 + n]
        i += 12 + n
    return zlib.decompress(idat)


